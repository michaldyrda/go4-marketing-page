// Writes the stylesheet as a file (dist/marketing-page.css) and its CSP hash
// (src/cssHash.ts). Run by `npm run build`; `npm test` fails if the hash in
// src/cssHash.ts no longer matches MARKETING_CSS (forgotten rebuild).
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { transformSync } from "esbuild";

const root = new URL("..", import.meta.url);
const ts = readFileSync(new URL("src/styles.ts", root), "utf8");
const { code } = transformSync(ts, { loader: "ts", format: "esm" });
const { MARKETING_CSS } = await import(
  "data:text/javascript;base64," + Buffer.from(code).toString("base64")
);

const hash = createHash("sha256").update(MARKETING_CSS, "utf8").digest("base64");
writeFileSync(
  new URL("src/cssHash.ts", root),
  `/** CSP hash of MARKETING_CSS for \`style-src 'sha256-…'\` (generated by scripts/css.mjs). */\n` +
    `export const MARKETING_CSS_SHA256 = "sha256-${hash}";\n`,
);
if (process.argv.includes("--write-dist")) {
  mkdirSync(new URL("dist", root), { recursive: true });
  writeFileSync(new URL("dist/marketing-page.css", root), MARKETING_CSS.trimStart());
}
console.log(`css: sha256-${hash}`);
